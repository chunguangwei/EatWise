/// 记录四态同步状态（《规格-数据同步与四态持久化》§1.1，D-20）。
///
/// 所有四态实体（FoodEntry 等）本地库统一携带；状态落库而非内存，
/// 杀进程/断网后可恢复（§1.1 关键不变式）。
enum SyncStatus {
  /// 提交中：乐观更新已入账，上行请求在途（含 D-11 撤销 10 秒窗内的待上行期）。
  submitting,

  /// 已同步：服务端已确认入库，本地持有服务端版本号与时间戳。
  synced,

  /// 待同步：上行失败（网络/5xx/离线写入）待重试，计入「待同步 N 条」入口。
  pending,

  /// 冲突：版本/etag 不匹配且自动合并未覆盖，需人工处理。
  conflicted,
}
